#!/usr/bin/env node
/**
 * Build frontend/set-art-embedded.js from local pokesymbols + set-images.
 * Seeded into Sets so covers/symbols paint before the API round-trip.
 *
 *   node scripts/build-set-art-embedded.js
 */
const fs = require("fs");
const fsp = require("fs/promises");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const MANIFEST_PATH = path.join(ROOT, "backend", "data", "pokesymbols", "manifest.json");
const SET_IMAGE_DIR = path.join(ROOT, "backend", "data", "set-images");
const OUT_PATH = path.join(ROOT, "frontend", "set-art-embedded.js");

const IMAGE_EXTS = new Set([".png", ".jpg", ".jpeg", ".webp", ".gif", ".avif"]);

function isLfsPointer(buf) {
  if (!Buffer.isBuffer(buf) || buf.length < 40) return false;
  const head = buf.subarray(0, 60).toString("utf8");
  return head.startsWith("version https://git-lfs.github.com/spec/v1");
}

function slugify(value) {
  return String(value || "")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function isLikelySetCode(value) {
  return /^[a-z0-9]{2,12}$/i.test(String(value || "").trim());
}

function toEncodedImageUrl(baseRoute, relPath) {
  const encodedRel = String(relPath)
    .split(/[/\\]/)
    .filter(Boolean)
    .map((segment) => encodeURIComponent(segment))
    .join("/");
  return `/${baseRoute}/${encodedRel}`;
}

function parseSetImageStem(stemValue) {
  const stem = String(stemValue || "").trim();
  if (!stem) return { left: "", right: "", parenCode: "" };
  const lowerStem = stem.toLowerCase();
  const [leftRaw, ...rightParts] = lowerStem.split("--");
  const left = leftRaw.trim();
  const right = rightParts.join("--").trim();
  const codeInParens = lowerStem.match(/\(([a-z0-9-]{2,12})\)\s*$/i);
  const parenCode = codeInParens ? codeInParens[1].toLowerCase() : "";
  return { left, right, parenCode };
}

async function walkImages(rootDir, relativeDir = "") {
  const absoluteDir = path.join(rootDir, relativeDir);
  let entries;
  try {
    entries = await fsp.readdir(absoluteDir, { withFileTypes: true });
  } catch {
    return [];
  }
  const out = [];
  for (const entry of entries) {
    const relPath = path.join(relativeDir, entry.name);
    if (entry.isDirectory()) {
      out.push(...(await walkImages(rootDir, relPath)));
      continue;
    }
    if (!entry.isFile()) continue;
    if (!IMAGE_EXTS.has(path.extname(entry.name).toLowerCase())) continue;
    out.push(relPath);
  }
  return out;
}

async function buildSetImageMaps() {
  const byCode = {};
  const byName = {};
  const imageFiles = await walkImages(SET_IMAGE_DIR);
  for (const relPath of imageFiles) {
    const absPath = path.join(SET_IMAGE_DIR, relPath);
    try {
      const head = await fsp.readFile(absPath);
      if (isLfsPointer(head)) continue;
    } catch {
      continue;
    }
    const relSegments = relPath.split(path.sep).filter(Boolean);
    const codeFromDir = relSegments.length > 1 ? String(relSegments[0]).toLowerCase().trim() : "";
    const stem = path.parse(path.basename(relPath)).name.trim();
    if (!stem) continue;
    const urlPath = toEncodedImageUrl("set-images", relPath);
    const { left, right, parenCode } = parseSetImageStem(stem);
    if (isLikelySetCode(codeFromDir) && !byCode[codeFromDir]) byCode[codeFromDir] = urlPath;
    if (isLikelySetCode(left) && !byCode[left]) byCode[left] = urlPath;
    if (parenCode && !byCode[parenCode]) byCode[parenCode] = urlPath;
    const rawNameCandidate = (right || stem.toLowerCase()).replace(/\([a-z0-9-]{2,12}\)\s*$/i, "").trim();
    const slugName = slugify(rawNameCandidate);
    if (slugName && !byName[slugName]) byName[slugName] = urlPath;
  }
  return { byCode, byName };
}

function buildPokesymbolsByCode(manifest) {
  const src = manifest && manifest.byCode && typeof manifest.byCode === "object" ? manifest.byCode : {};
  const out = {};
  for (const [code, row] of Object.entries(src)) {
    if (!row || typeof row !== "object") continue;
    const logo = String(row.logo || "").trim();
    const symbol = String(row.symbol || "").trim();
    if (!logo && !symbol) continue;
    out[String(code).trim()] = {
      slug: String(row.slug || "").trim(),
      logo,
      symbol
    };
  }
  return out;
}

async function main() {
  const manifest = JSON.parse(await fsp.readFile(MANIFEST_PATH, "utf8"));
  const pokesymbolsByCode = buildPokesymbolsByCode(manifest);
  const { byCode: imagesByCode, byName: imagesByName } = await buildSetImageMaps();
  const payload = {
    generatedAt: new Date().toISOString(),
    pokesymbolsByCode,
    imagesByCode,
    imagesByName
  };
  const body =
    "/* AUTO-GENERATED by scripts/build-set-art-embedded.js — do not edit */\n" +
    `window.__POKEMONVIEW_SET_ART__=${JSON.stringify(payload)};\n`;
  await fsp.writeFile(OUT_PATH, body, "utf8");
  console.log(
    `[set-art] wrote ${path.relative(ROOT, OUT_PATH)} ` +
      `(pokesymbols=${Object.keys(pokesymbolsByCode).length} ` +
      `setImages=${Object.keys(imagesByCode).length} ` +
      `${(Buffer.byteLength(body) / 1024).toFixed(1)}KB)`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
