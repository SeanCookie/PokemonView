/**
 * Embed shared frontend assets into the Worker so edge can fix stale container
 * HTML/assets without waiting for a Docker image rebuild.
 *
 *   node scripts/embed-frontend-overrides.js
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const cssPath = path.join(ROOT, "frontend", "site-nav.css");
const jsPath = path.join(ROOT, "frontend", "site-nav.js");
const setsPath = path.join(ROOT, "frontend", "sets.html");
const faviconSvgPath = path.join(ROOT, "frontend", "favicon.svg");
const faviconPngPath = path.join(ROOT, "frontend", "favicon.png");
const appleTouchPath = path.join(ROOT, "frontend", "apple-touch-icon.png");
const outPath = path.join(ROOT, "cloudflare", "frontend-overrides.generated.js");

const css = fs.readFileSync(cssPath, "utf8");
const js = fs.readFileSync(jsPath, "utf8");
const setsHtml = fs.readFileSync(setsPath, "utf8");
const faviconSvg = fs.readFileSync(faviconSvgPath, "utf8");
const faviconPngBase64 = fs.readFileSync(faviconPngPath).toString("base64");
const appleTouchPngBase64 = fs.existsSync(appleTouchPath)
  ? fs.readFileSync(appleTouchPath).toString("base64")
  : faviconPngBase64;

const out = `/* AUTO-GENERATED by scripts/embed-frontend-overrides.js — do not edit */
export const SITE_NAV_CSS = ${JSON.stringify(css)};
export const SITE_NAV_JS = ${JSON.stringify(js)};
export const SETS_HTML = ${JSON.stringify(setsHtml)};
export const FAVICON_SVG = ${JSON.stringify(faviconSvg)};
export const FAVICON_PNG_BASE64 = ${JSON.stringify(faviconPngBase64)};
export const APPLE_TOUCH_ICON_PNG_BASE64 = ${JSON.stringify(appleTouchPngBase64)};
`;

fs.writeFileSync(outPath, out, "utf8");
// eslint-disable-next-line no-console
console.log(
  `[embed] wrote ${path.relative(ROOT, outPath)} (css ${css.length}b, js ${js.length}b, sets ${setsHtml.length}b, favicon svg ${faviconSvg.length}b)`
);
